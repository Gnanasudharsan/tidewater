#!/usr/bin/env bash
# Extract a small, internally consistent slice of the warehouse's silver schema as
# the fixture dbt CI builds against: 6 orders per status plus 3 deleted orders, with
# all their lines, payments and customers, and the full product catalog.
#   scripts/make_ci_fixture.sh   (writes dbt/ci/silver_fixture.sql)
set -euo pipefail
cd "$(dirname "$0")/.."
PSQL=(docker compose exec -T postgres-wh psql -q -v ON_ERROR_STOP=1 -U warehouse -d analytics)
"${PSQL[@]}" <<'SQL'
drop schema if exists ci_fixture cascade;
create schema ci_fixture;
create table ci_fixture.orders as
  select * from (
    select o.*, row_number() over (partition by status order by order_id) as rn
    from silver.orders o where not is_deleted
  ) x where rn <= 6
  union all
  select *, 0 from (select * from silver.orders where is_deleted order by order_id limit 3) d;
alter table ci_fixture.orders drop column rn;
create table ci_fixture.order_items as
  select * from silver.order_items where order_id in (select order_id from ci_fixture.orders);
create table ci_fixture.payments as
  select * from silver.payments where order_id in (select order_id from ci_fixture.orders);
create table ci_fixture.customers as
  select * from silver.customers where customer_id in (select customer_id from ci_fixture.orders);
create table ci_fixture.products as select * from silver.products;
SQL
{
  echo "-- Generated by scripts/make_ci_fixture.sh from synthetic (Faker) data. Do not edit."
  docker compose exec -T postgres-wh pg_dump -U warehouse -d analytics -n ci_fixture \
    --no-owner --no-privileges --no-comments \
    | grep -vE '^(CREATE SCHEMA|SELECT pg_catalog.set_config|SET |--|$)' \
    | sed 's/ci_fixture\./silver./g'
} > dbt/ci/silver_fixture.sql
"${PSQL[@]}" -c "drop schema ci_fixture cascade"
wc -l dbt/ci/silver_fixture.sql
